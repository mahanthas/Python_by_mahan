word = "MAHANTHA SWAMY"

print(word.lower()) # mahantha swamy
print(word.upper()) # MAHANTHA SWAMY
print(word.title()) # Mahantha swamy
print(word.strip(" ")) # removes starting and ending whitespaces
print(word.replace("A",'B')) # MBHBNTHB SWBMY
print(word.split()) # converts string to list 
print(word.join(" L")) # MAHANTHA SWAMY L
print(word.startswith('M'))
print(word.endswith('Y'))
print(word.find('W'))
print(word.count('A'))
print(word.isalnum())
print(word.isdigit())
print(word.isalpha())